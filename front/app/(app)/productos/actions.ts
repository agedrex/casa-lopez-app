"use server";

import { redirect } from "next/navigation";
import { error, type FormState } from "@/lib/action-state";
import { apiPost } from "@/lib/api";
import {
  resolveCatalogChoice,
  resolveCueroChoice,
} from "@/lib/catalogo-actions";
import { todayIso } from "@/lib/format";
import type { Ficha } from "@/lib/types";
import {
  denyUnlessWriter,
  fromFailure,
  optional,
  text,
} from "@/lib/write-guard";
import { NUEVO_CATALOGO } from "./catalogo-nuevo";

const QUIEN = ["EXTERNA", "INTERNA"];

export async function createProducto(
  _previous: FormState,
  formData: FormData,
): Promise<FormState> {
  const denied = await denyUnlessWriter();
  if (denied) return denied;

  const esKit = formData.get("es_kit") === "on";
  const modelo = optional(formData, "modelo");
  const quien = text(formData, "quien_lo_confecciona");
  if (!modelo && !esKit) {
    return error("Elija el modelo (solo un kit puede ir sin modelo).");
  }
  if (!text(formData, "cuero") && !esKit) return error("Elija el cuero.");
  if (!QUIEN.includes(quien)) return error("Indique quién lo confecciona.");

  // "+ Crear color nuevo…": the color is created first (its code is generated by the API).
  const color = await resolveCatalogChoice({
    formData,
    field: "color",
    newField: "color_nuevo",
    sentinel: NUEVO_CATALOGO,
    path: "/colores",
    noun: "el color nuevo",
  });
  if (!color.ok) return color.state;

  // "+ Crear cuero nuevo…": the leather (a material without price) is created first.
  const cuero = await resolveCueroChoice({
    formData,
    field: "cuero",
    newField: "cuero_nuevo",
    sentinel: NUEVO_CATALOGO,
  });
  if (!cuero.ok) return cuero.state;

  const result = await apiPost<Ficha>("/productos", {
    modelo,
    cuero: cuero.codigo,
    color: color.nombre,
    quien_lo_confecciona: quien,
    // Automatic: the sheet date is today in Buenos Aires, never typed.
    fecha_de_alta: todayIso(),
    nombre_propio: optional(formData, "nombre_propio"),
    es_kit: esKit,
    nota: optional(formData, "nota"),
  });
  if (!result.ok) return fromFailure(result);
  redirect(`/productos/${encodeURIComponent(result.data.codigo)}`);
}
